#!/usr/bin/env julia


mutable struct Dice
    seed::Int
    pulse::Int
    nroll::Int
    face::Int
    faces::NTuple
    function Dice(faces::AbstractVector{Int}, seed::Int)
        new(seed, seed, 0, 1, tuple(faces...))
    end
end


value(d::Dice) = d.faces[d.face]


function roll!(d::Dice)
    d.nroll += 1
    spin = d.nroll * d.pulse
    d.pulse = (d.pulse + spin) % d.seed + d.nroll + d.seed + 1
    d.face = 1 + (d.face - 1 + spin) % length(d.faces)
    return value(d)
end


function parsedice(text)
    map(split(text, '\n', keepempty=false)) do s
        x = [parse(Int, m.match) for m in eachmatch(r"-?\d+", s)]
        Dice(x[2:end-1], x[end])
    end
end


function parsetrack(text)
    s, t = split(text, "\n\n", keepempty=false)
    d = parsedice(s)
    v = parse.(Int, collect(strip(t)))
    return (d, v)
end


function parsegrid(text)
    s, t = split(text, "\n\n", keepempty=false)
    d = parsedice(s)
    v = parse.(Int, stack(split(t), dims=1))
    return (d, v)
end


function race!(d::Dice, v::AbstractVector{Int})
    n = length(v)
    p = 1
    for t in Iterators.countfrom()
        roll!(d) == v[p] && (p += 1)
        p > n && return t
    end
end


function fit!(d::Dice, g::AbstractArray{Int,2})
    neibs = [(0,0),(-1,0),(1,0),(0,-1),(0,1)] .|> CartesianIndex
    x = roll!(d)
    fringe = Set(findall(==(x), g))
    seen = empty(fringe)
    for t in Iterators.countfrom()
        union!(seen, fringe)
        x = roll!(d)
        dawn = empty(fringe)
        for p in fringe, d in neibs
            if get(g, p+d, nothing) == x
                push!(dawn, p+d)
            end
        end
        isempty(dawn) && return seen
        fringe = dawn
    end
end


function part1(data, N=10000)
    dice = parsedice(data)
    s = 0
    for t in Iterators.countfrom()
        s += sum(roll!.(dice))
        s >= N && return t
    end
end


function part2(data)
    dice, track = parsetrack(data)
    r = race!.(dice, [track])
    xi = sort([(x,i) for (i,x) in enumerate(r)])
    join((i for (_,i) in xi), ',')
end


function part3(data)
    dice, grid = parsegrid(data)
    reduce(union!, fit!.(dice, [grid])) |> length
end


